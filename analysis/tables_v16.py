"""LaTeX table of the round 4 blocks for the electronic supplement.

Usage: python analysis/tables_v16.py <agg dir with v16_*.csv> --out <tables dir>
Percentage points: mean and 95% interval; bold when the interval excludes zero; parentheses when not evaluable.
"""
import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
from tables_v15 import fmt, get  # noqa: E402

COLS = ["TAB", "TS", "GRA", "TXT"]
H2B_ROWS = [(r"$G^*(P_{0.4})$", "G*(P40)"), (r"$\Delta^{*P}_{0.2}$", "Delta*^P_20"), (r"$\Delta^{*P}_{0.4}$", "Delta*^P_40"),
            (r"$G(P_{0.4})$", "G(P40)"), (r"$\Delta^{P}_{0.4}$", "Delta^P_40"),
            (r"$\Delta^{*D}_{0.2}$", "Delta*^D_20"), (r"$\Delta^{*D}_{0.4}$", "Delta*^D_40"),
            (r"$G^*(JD_{0.4})-G^*(J_{0.4})$", "G*(JD40)-G*(J40)"),
            (r"$A_{\mathrm{CE}}(JD_{0.4})-A_{\mathrm{CE}}(J_{0.4})$", "A_CE(JD40)-A_CE(J40)"),
            (r"$A_{\mathrm{CE}}(JD_{0.4})-A_{\mathrm{CE}}(L_{0.4})$", "A_CE(JD40)-A_CE(L40)"),
            (r"$A_{\mathrm{FC}^*}(JD_{0.4})-A_{\mathrm{FC}^*}(J_{0.4})$", "A_FC*(JD40)-A_FC*(J40)"),
            (r"$D^{P}_{0.4}$", "D^P_40")]
SC_ROWS = [(r"$D^{SC}_{0.2}$", "D^SC_0.2"), (r"$D^{SC}_{0.4}$", "D^SC_0.4"), (r"$D^{SC}_{AT}$", "D^SC_AT"),
           (r"$\mathrm{RLA}^{SC}(A_{0.4})-\mathrm{RLA}(A_{0.4})$", "RLA^SC(A40)-RLA(A40)"),
           (r"$\Delta^{*SC}_{0.4}$", "Delta*^SC_0.4")]


def main():
    a = argparse.ArgumentParser()
    a.add_argument("agg")
    a.add_argument("--out", required=True)
    o = a.parse_args()
    h2b = pd.read_csv(os.path.join(o.agg, "v16_h2b.csv"))
    sc = pd.read_csv(os.path.join(o.agg, "v16_sc.csv"))
    L = [r"% Generated by analysis/tables_v16.py; regenerate rather than edit.",
         r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
         r"\caption{Fourth round (five seeds on the RTX 4090; percentage points, mean and 95\% interval; bold: the "
         r"interval excludes zero; parentheses: not evaluable). H2B: pair label noise alone ($P_\rho$) and with "
         r"independent input noise ($JP_\rho$), and symmetric label noise on exactly the examples with corrupted inputs "
         r"($JD_\rho$); $\Delta^{P}$ and $\Delta^{*P}$ compare $JP_\rho$ with $P_\rho$, $\Delta^{*D}$ compares $JD_\rho$ "
         r"with $L_\rho$; the rows of test accuracies $A_{\mathrm{CE}}$ and $A_{\mathrm{FC}^*}$ (post hoc) split the "
         r"change of $G^*$ from $J_{0.4}$ to $JD_{0.4}$ into its CE and FC$^*$ parts, and compare CE under $JD_{0.4}$ with the same label noise on clean inputs ($L_{0.4}$). SC: input noise standardised with statistics "
         r"of the clean training set.}\label{tab:emp-v16}",
         r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}X*{4}{c}@{}}", r"\toprule",
         "Statistic & " + " & ".join(COLS) + r" \\", r"\midrule",
         r"\multicolumn{5}{@{}l}{\textit{Pair and input-dependent label noise (H2B)}} \\"]
    for lab, st in H2B_ROWS:
        L.append(lab + " & " + " & ".join(fmt(get(h2b, dataset=d, statistic=st)) for d in COLS) + r" \\")
    L.append(r"\multicolumn{5}{@{}l}{\textit{Clean-set standardisation (SC)}} \\")
    for lab, st in SC_ROWS:
        L.append(lab + " & " + " & ".join(fmt(get(sc, dataset=d, statistic=st)) for d in COLS) + r" \\")
    L += [r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
    os.makedirs(o.out, exist_ok=True)
    open(os.path.join(o.out, "emp_v16.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
