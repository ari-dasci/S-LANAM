"""LaTeX table of the round 5 block and its round 5 extension for the electronic supplement.

Usage: python analysis/tables_v17.py <agg dir with v17_oos.csv> --out <tables dir>
Percentage points: mean and 95% interval; bold when the interval excludes zero; parentheses when not evaluable.
Errors of T_hat: Frobenius norm of T_hat - T over the number of classes, times 100 (means over seeds).
"""
import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
from tables_v15 import fmt, get  # noqa: E402

MODS = ["Tab", "Img", "Txt", "TS", "Graph", "Audio"]
GRID = ["TAB", "IMG", "TXT", "TS", "GRA", "AUD"]
SECOND = ["TAB2", "IMG2", "TXT2", "TS2", "GRA2", "AUD2"]
ROWS = [(r"$G_{\mathrm{OOS}}(L_{0.2})$", "G_OOS(L20)", "ci"), (r"$G_{\mathrm{OOS}}(L_{0.4})$", "G_OOS(L40)", "ci"),
        (r"$\Delta_{\mathrm{OOS},0.2}$", "Delta_OOS_20", "ci"), (r"$\Delta_{\mathrm{OOS},0.4}$", "Delta_OOS_40", "ci"),
        (r"$G_{\mathrm{cal}}(L_{0.2})$", "G_cal(L20)", "ci"), (r"$G_{\mathrm{cal}}(L_{0.4})$", "G_cal(L40)", "ci"),
        (r"$\Delta_{\mathrm{cal},0.2}$", "Delta_cal_20", "ci"), (r"$\Delta_{\mathrm{cal},0.4}$", "Delta_cal_40", "ci"),
        (r"$G_{\mathrm{cal}}(L_{0.4})-G_{\mathrm{OOS}}(L_{0.4})$", "G_cal-G_OOS(L40)", "ci"),
        (r"$G(L_{0.4})$, in-sample $\hat T$ (descriptive)", "G_grid(L40)", "mean"),
        (r"Inverse temperature $\beta$ at $L_{0.4}$", "beta(L40)", "raw"),
        (r"Error of $\hat T$ at $L_{0.4}$ ($\times100$): in-sample, global rule", "errT_IS_global(L40)", "mean"),
        (r"\quad out-of-sample, class-wise rule (OOS)", "errT_OOS_class(L40)", "mean"),
        (r"\quad out-of-sample, arg-max rule", "errT_OOS_argmax(L40)", "mean"),
        (r"\quad calibrated, class-wise rule (cal)", "errT_cal_class(L40)", "mean"),
        (r"\quad identity ($\hat T=I$, FC $\equiv$ CE)", "errT_identity(L40)", "mean"),
        (r"Change, OOS minus grid rule ($\times100$)", "errT_OOS-errT_IS(L40)", "bold"),
        (r"Change, cal minus OOS ($\times100$)", "errT_cal-errT_OOS(L40)", "bold")]


def cell(df, ds, st, kind):
    r = get(df, dataset=ds, statistic=st)
    if r is None or str(r.get("mean", "")) in ("", "nan"):
        return "--"
    if kind == "bold":                                  # mean only, bold when the interval excludes zero
        return fmt(r, interval=False)
    if kind == "raw":
        return f"{float(r['mean']):.2f}"
    if kind == "mean":
        return fmt(dict(mean=r["mean"], lo="", hi=""))
    return fmt(r)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("agg")
    a.add_argument("--out", required=True)
    o = a.parse_args()
    df = pd.read_csv(os.path.join(o.agg, "v17_oos.csv"))
    L = [r"% Generated by analysis/tables_v17.py; regenerate rather than edit.",
         r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2.5pt}",
         r"\caption{Fifth round: forward correction with $\hat T$ from two-fold cross-fitted (out-of-sample) "
         r"predictions and the class-wise anchor rule (OOS), and from the same predictions calibrated by temperature "
         r"(cal; five seeds; percentage points, mean and 95\% interval; bold: "
         r"the interval excludes zero, before correction for multiplicity; parentheses: not evaluable). $G_{\mathrm{OOS}}(u)$ and $G_{\mathrm{cal}}(u)$: "
         r"accuracy of FC with each $\hat T$ minus that of CE, all on the same card; $\Delta_{\mathrm{OOS},\rho}="
         r"G_{\mathrm{OOS}}(J_\rho)-G_{\mathrm{OOS}}(L_\rho)$, and likewise $\Delta_{\mathrm{cal},\rho}$. $G(L_{0.4})$ "
         r"uses the in-sample estimate of the grid or of the second datasets, possibly on another card; in-sample errors use the CE of the same cell. $\beta$: mean "
         r"inverse temperature. Errors of $\hat T$: $\|\hat T-T\|_F/c$; the identity "
         r"row is the error of assuming no noise.}\label{tab:emp-v17}",
         r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}X*{6}{c}@{}}", r"\toprule",
         "Statistic & " + " & ".join(MODS) + r" \\", r"\midrule"]
    for title, dss in ((r"Datasets of the grid", GRID), (r"Second datasets", SECOND)):
        L.append(r"\multicolumn{7}{@{}l}{\textit{" + title + r"}} \\")
        for lab, st, kind in ROWS:
            L.append(lab + " & " + " & ".join(cell(df, d, st, kind) for d in dss) + r" \\")
    L += [r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
    os.makedirs(o.out, exist_ok=True)
    open(os.path.join(o.out, "emp_v17.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
