"""LaTeX tables of the round 3 blocks for the electronic supplement.

Usage: python analysis/tables_v15.py <agg dir with v15_*.csv> --grid <grid analysis dir> --mult <multiplicity dir>
       --out <tables dir>
Values in percentage points: mean and 95% interval; bold when the interval excludes zero; in parentheses when
the statistic is not evaluable (its precondition fails).
"""
import argparse
import os

import pandas as pd

MODS = ["TAB", "IMG", "TXT", "TS", "GRA", "AUD"]


def sgn(v, digits=1):
    return (f"{v:+.{digits}f}").replace("-", "$-$")


def fmt(r, scale=100, digits=1, interval=True):
    if r is None:
        return "--"
    if str(r.get("lo", "")) in ("", "nan"):
        return "--" if str(r.get("mean", "")) in ("", "nan") else sgn(scale * float(r["mean"]), digits)
    m, lo, hi = (scale * float(r[k]) for k in ("mean", "lo", "hi"))
    main = sgn(m, digits)
    if r.get("conclusion") == "not evaluable":
        main = "(" + main + ")"
    elif lo > 0 or hi < 0:
        main = r"\textbf{" + main + "}"
    if not interval:
        return main
    return r"\makecell{" + main + r"\\{\tiny[" + sgn(lo, digits) + ", " + sgn(hi, digits) + "]}}"


def get(df, **kw):
    if df is None or not len(df):
        return None
    s = df
    for k, v in kw.items():
        s = s[s[k].astype(str) == str(v)]
    return s.iloc[0] if len(s) else None


def table_v15(te, dr, out):
    L = [r"% Generated by analysis/tables_v15.py; regenerate rather than edit.",
         r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2.5pt}",
         r"\caption{Third round of exploratory blocks (five seeds; percentage points, mean and 95\% interval; bold: "
         r"the interval excludes zero; parentheses: not evaluable). TE: forward correction with $\hat T$ estimated from "
         r"an early-stopped CE model (the change in the error of $\hat T$ averages $L_{0.4}$ and $J_{0.4}$ within each seed); DR: "
         r"relative loss of accuracy under input noise on 40\% of the examples at severities 1--7, against label noise on "
         r"40\%. Each RLA uses clean and $L_{0.4}$ runs of its own card, so the last row, from the card of severities "
         r"4--6, can differ slightly from the reference of the other severities for images and audio.}\label{tab:emp-v15}",
         r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}X*{6}{c}@{}}", r"\toprule",
         "Statistic & " + " & ".join(MODS) + r" \\", r"\midrule",
         r"\multicolumn{7}{@{}l}{\textit{$\hat T$ from an early-stopped model (TE)}} \\"]
    rows = [(r"$G_{ES}(L_{0.2})$", "G_ES(L20)"), (r"$\Delta_{ES,0.2}$", "Delta_ES_20"),
            (r"$G_{ES}(L_{0.4})$", "G_ES(L40)"), (r"$\Delta_{ES,0.4}$", "Delta_ES_40"),
            (r"Change in error of $\hat T$ ($\rho=0.4$, $\times 100$)", "errT_ES-errT_grid(40)")]
    for lab, st in rows:
        L.append(lab + " & " + " & ".join(fmt(get(te, dataset=m, statistic=st)) for m in MODS) + r" \\")
    L.append(r"\multicolumn{7}{@{}l}{\textit{Dose--response of H1 (DR)}} \\")
    for lv in range(1, 8):
        lab = rf"$\mathrm{{RLA}}(A_{{0.4}})$, severity {lv}"
        L.append(lab + " & " + " & ".join(fmt(get(dr, dataset=m, statistic=f"RLA(A40-l{lv})")) for m in MODS) + r" \\")
    L.append(r"$\mathrm{RLA}(L_{0.4})$ & " + " & ".join(fmt(get(dr, dataset=m, statistic="RLA(L40)")) for m in MODS)
             + r" \\")
    L += [r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
    open(out, "w").write("\n".join(L) + "\n")


def table_cv_h4x(cv, h4x, grid_h, grid_rF, out):
    L = [r"% Generated by analysis/tables_v15.py; regenerate rather than edit.",
         r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
         r"\caption{Audio with the ten official folds of UrbanSound8K (one seed per fold; corrected resampled $t$ "
         r"intervals with 9 degrees of freedom~\citep{nadeau2003inference}) against the grid (fold 10 as test, five seeds), and H4 with two more annotators per modality "
         r"(five seeds), with the annotator of the grid for reference. Percentage points; marks as in \cref{tab:emp-v15}; $r_F$ in percent; $^{\ddagger}$: $r_F<5\%$, uninformative (\cref{app:fm-labels}). A row maximum of $T_F$ lies off the diagonal for the "
         r"annotator of the grid on audio, Qwen2.5-3B, Phi-3.5-mini and CLAP 630k (air conditioner labelled engine idling; Sci/Tech labelled Business).}\label{tab:emp-cv-h4x}",
         r"\begin{tabular}{@{}lcc@{\hspace{12pt}}llccc@{}}", r"\toprule",
         r"\multicolumn{3}{@{}c}{Audio, H1--H4} & \multicolumn{5}{c@{}}{H4, more annotators} \\",
         r"\cmidrule(r{6pt}){1-3}\cmidrule(l){4-8}",
         r"Statistic & Grid & 10 folds & Modality & Annotator & $r_F$ & $E$ & $\Delta_F$ \\", r"\midrule"]
    left = [(r"$A_{0\%}$", "acc_c0", None), (r"$D_{0.2}$", "D_0.2", ("D", 0.2)), (r"$D_{0.4}$", "D_0.4", ("D", 0.4)),
            (r"$G(L_{0.4})$", "G(L40)", ("G(L)", 0.4)), (r"$G^*(L_{0.4})$", "G*(L40)", ("G*(L)", 0.4)),
            (r"$\Delta^*_{0.4}$", "Delta*_0.4", ("Delta*", 0.4)), (r"$E$", "E", ("E", None)),
            (r"$G^*(C)$", "G*(C)", ("G*(C)", None)), (r"$\Delta_F$", "Delta_F", ("Delta_F", None))]
    right = []
    names = {("IMG", "0"): "CLIP RN50 (grid)", ("IMG", "1"): "CLIP ViT-B/16", ("IMG", "2"): "CLIP ViT-L/14",
             ("TXT", "0"): "Qwen2.5-7B (grid)", ("TXT", "1"): "Qwen2.5-3B", ("TXT", "2"): "Phi-3.5-mini",
             ("AUD", "0"): "CLAP 630k-AS (grid)", ("AUD", "1"): "CLAP 630k", ("AUD", "2"): "CLAP music-speech"}
    for ds in ("IMG", "TXT", "AUD"):
        g = grid_h[(grid_h.dataset == ds) & (grid_h.pipeline == "N")]
        gE, gD = get(g, statistic="E"), get(g, statistic="Delta_F")
        right.append((ds, names[(ds, "0")], f"{100 * grid_rF[ds]:.1f}", fmt(gE, interval=False),
                      fmt(gD, interval=False)))
        for a in ("1", "2"):
            s = h4x[(h4x.dataset == ds) & (h4x.annotator.astype(str) == a)] if len(h4x) else h4x
            if not len(s):
                continue
            rf = get(s, statistic="r_F")
            rfv = 100 * float(rf["mean"]) if rf is not None else float("nan")
            mark = r"$^{\ddagger}$" if rfv < 5 else ""
            right.append(("", names[(ds, a)] + mark, f"{rfv:.1f}", fmt(get(s, statistic="E"), interval=False),
                          fmt(get(s, statistic="Delta_F"), interval=False)))
    for i in range(max(len(left), len(right))):
        if i < len(left):
            lab, st, g = left[i]
            cvv = get(cv, statistic=st)
            if g is None:
                gv = "72.7"
                lv = f"{100 * float(cvv['mean']):.1f}" if cvv is not None else "--"
            else:
                gr = grid_h[(grid_h.dataset == "AUD") & (grid_h.pipeline == "N") & (grid_h.statistic == g[0])]
                if g[1] is not None:
                    gr = gr[gr.rho == g[1]]
                gv = fmt(gr.iloc[0], interval=False) if len(gr) else "--"
                lv = fmt(cvv, interval=False)
            lcells = f"{lab} & {gv} & {lv}"
        else:
            lcells = " & & "
        rcells = " & ".join(right[i]) if i < len(right) else " & & & & "
        L.append(lcells + " & " + rcells + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(out, "w").write("\n".join(L) + "\n")


NAMES = {"Interaction I": r"Interaction $I_\rho$", "H1 other severities": "H1, other severities",
         "E1": "E1, strong input noise", "LS": "Loss separability", "H1C": "Controls of H1",
         "CN": "CIFAR-10N (CN)", "ES": "Early stopping (ES)", "H2P": "Stronger corrections",
         "CD": "Cora at 200 and 400 epochs (CD)", "H3C-FT": "Controls of H3: FT", "H3C-MH": "Controls of H3: MH",
         "H3C-RN": "Controls of H3: RN", "D2": "Second datasets",
         "H2B": "H2B, pair and input-dependent label noise", "SC": "SC, clean-set standardisation",
         "OOS": r"OOS, out-of-sample $\hat T$", "OOSC accuracy": r"OOS, calibrated $\hat T$: accuracy",
         "OOSC error of T_hat": r"OOS, calibrated $\hat T$: error of $\hat T$",
         "H3 paired contrasts": "H3, paired contrasts between pipelines (post hoc)"}


def table_mult(summ, out):
    order = ["H1", "H2 (evaluable)", "H3", "H4a", "H4b (evaluable)", "H2* (evaluable)", "H3 paired contrasts", "Interaction I",
             "H1 other severities", "E1"]
    L = [r"% Generated by analysis/tables_v15.py; regenerate rather than edit.",
         r"\begin{table}[tbp]", r"\centering", r"\scriptsize",
         r"\caption{Multiplicity and equivalence. Families: H1--H4 (Holm) and exploratory (Benjamini--Hochberg, "
         r"$q=0.05$; the calibrated block in two families by kind of statistic). The H3 family holds the statistics within each "
         r"frozen pipeline; the paired contrasts between pipelines form a post hoc family. Equivalent: not distinguishable from zero "
         r"and within $\pm1$ point by two one-sided tests at 5\%; changes of the error of $\hat T$ are not tested "
         r"for equivalence. Statistics outside these families are unadjusted.}"
         r"\label{tab:emp-mult}",
         r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule",
         r"Family & Correction & Tests & Significant & After correction & Equivalent to 0 \\", r"\midrule"]
    s = summ.copy()
    s["o"] = [order.index(f) if f in order else 100 + i for i, f in enumerate(s.family)]
    prev = None
    for _, r in s.sort_values("o").iterrows():
        if prev == "main" and r.kind != "main":
            L.append(r"\midrule")
        prev = r.kind
        fam = str(r.family).replace("v1.4 ", "").replace("v1.5 ", "").replace("v1.6 ", "").replace("v1.7 ", "").replace("v1.8 ", "")
        fam = NAMES.get(fam, fam).replace("*", "$^*$")
        L.append(f"{fam} & {'Holm' if r.kind == 'main' else 'BH'} & {int(r.tests)} & {int(r.sig_raw)} & "
                 f"{int(r.sig_adj)} & {int(r.equiv)} " + r"\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(out, "w").write("\n".join(L) + "\n")


def main():
    a = argparse.ArgumentParser()
    a.add_argument("agg")
    a.add_argument("--grid", required=True)
    a.add_argument("--mult", required=True)
    a.add_argument("--out", required=True)
    o = a.parse_args()

    def rd(k):
        p = os.path.join(o.agg, f"v15_{k}.csv")
        return pd.read_csv(p) if os.path.exists(p) and os.path.getsize(p) > 2 else pd.DataFrame()

    te, dr, cv, h4x = rd("te"), rd("dr"), rd("cv"), rd("h4x")
    grid_h = pd.read_csv(os.path.join(o.grid, "hypotheses.csv"))
    os.makedirs(o.out, exist_ok=True)
    table_v15(te, dr, os.path.join(o.out, "emp_v15.tex"))
    ann = pd.read_csv(os.path.join(o.grid, "annotators.csv"))
    grid_rF = dict(zip(ann.dataset, ann.r_F))
    table_cv_h4x(cv, h4x, grid_h, grid_rF, os.path.join(o.out, "emp_cv_h4x.tex"))
    table_mult(pd.read_csv(os.path.join(o.mult, "multiplicity_summary.csv")), os.path.join(o.out, "emp_mult.tex"))


if __name__ == "__main__":
    main()
