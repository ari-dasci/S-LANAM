def cell(st, ds, block, stat):
    s = st[(st.dataset == ds) & (st.block == block)]
    s = s[s.statistic.str.startswith(stat)] if stat.endswith("@") else s[s.statistic == stat]
    if not len(s) or str(s.iloc[0]["lo"]) in ("", "nan"):
        return "--"
    r = s.iloc[0]
    m, lo, hi = (100 * float(r[k]) for k in ("mean", "lo", "hi"))
    txt = f"{m:+.1f} [{lo:+.1f}, {hi:+.1f}]"
    return r"\textbf{" + txt + "}" if (lo > 0 or hi < 0) else txt


def main(paths, out):
    st = pd.concat([pd.read_csv(p, keep_default_na=False) for p in paths], ignore_index=True)
    L = [r"% Generated by analysis/tables_v14.py from v14_stats.csv (both machines); regenerate rather than edit.",
         r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2.5pt}",
         r"\caption{Exploratory blocks of the study (five seeds; percentage points, mean and 95\% interval; bold: the interval "
         r"excludes zero). Second-dataset rows use Covertype, CIFAR-100, DBpedia-14, ElectricDevices, CiteSeer and Speech "
         r"Commands in the columns of their modality.}\label{tab:emp-v14}",
         r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}X*{6}{c}@{}}", r"\toprule",
         "Statistic & " + " & ".join(MODS) + r" \\", r"\midrule"]
    for name, spec in ROWS:
        if spec is None:
            L.append(r"\multicolumn{7}{@{}l}{\textit{" + name + r"}} \\")
            continue
        block, stat, suf = spec
        L.append(name + " & " + " & ".join(cell(st, m + suf, block, stat) for m in MODS) + r" \\")
    L += [r"\bottomrule", r"\end{tabularx}", r"\end{table}", ""]
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("written", out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("stats", nargs="+")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    main(a.stats, a.out)
