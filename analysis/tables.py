"""LaTeX tables of Section 8 and Appendix C from the outputs of aggregate.py.

  python analysis/tables.py --analysis <RUNS>/analysis --out <manuscript>/tables

Writes emp_results.tex (H1 and H2, tab:emp-results), emp_h4.tex (tab:emp-h4), emp_full_native.tex
(tab:emp-full-native), emp_full_frozen.tex (tab:emp-full-frozen) and emp_that.tex (tab:emp-that).
With --e12 <E1/E2 runs>/analysis it also writes emp_e12.tex (tab:emp-e12) from the outputs of aggregate_e12.py.
Statistics are in percentage points; a superscript + or - marks a 95% interval above or below zero.
"""
import argparse
import os

import numpy as np
import pandas as pd

DATASETS = ["TAB", "IMG", "TXT", "TS", "GRA", "AUD"]
FM_DATASETS = ["IMG", "TXT", "AUD"]
NAMES = {"TAB": "Tabular", "IMG": "Images", "TXT": "Text", "TS": "Time series", "GRA": "Graphs", "AUD": "Audio"}
K = {"TAB": 26, "IMG": 10, "TXT": 4, "TS": 6, "GRA": 7, "AUD": 10}
MARK = {"positive": "$^{+}$", "negative": "$^{-}$"}


def stat(hyp, ds, pl, st, rho=None):
    s = hyp[(hyp.dataset == ds) & (hyp.pipeline == pl) & (hyp.statistic == st)]
    s = s[s.rho.isna()] if rho is None else s[np.isclose(s.rho.astype(float), rho)]
    return s.iloc[0] if len(s) else None


def num(hyp, ds, pl, st, rho=None, paren_if=None):
    r = stat(hyp, ds, pl, st, rho)
    if r is None or pd.isna(r["mean"]):
        return "--"
    v = round(100 * r["mean"], 1) + 0.0                    # + 0.0 turns -0.0 into 0.0
    txt = f"{v:.1f}".replace("-", "$-$") + MARK.get(r["conclusion"], "")
    return f"({txt})" if paren_if else txt


def write(path, lines):
    with open(path, "w", encoding="utf-8") as f:
        f.write("% Generated by analysis/tables.py from analysis/*.csv; do not edit by hand.\n" + "\n".join(lines) + "\n")


def main(analysis, out):
    os.makedirs(out, exist_ok=True)
    hyp = pd.read_csv(os.path.join(analysis, "hypotheses.csv"))
    summ = pd.read_csv(os.path.join(analysis, "summary.csv"))
    that = pd.read_csv(os.path.join(analysis, "that_error.csv"))
    ann = pd.read_csv(os.path.join(analysis, "annotators.csv"))

    def acc(ds, pl, m, cond):
        s = summ[(summ.dataset == ds) & (summ.pipeline == pl) & (summ.method == m) & (summ.condition == cond)]
        return s.iloc[0] if len(s) else None

    # ---- main table: H1 and H2 (rho = 0.4), with the relative error of T-hat
    rows = []
    for ds in DATASETS:
        a0 = acc(ds, "N", "CE", "c0")
        gl = stat(hyp, ds, "N", "G(L)", 0.4)
        gs = stat(hyp, ds, "N", "G*(L)", 0.4)
        e = that[(that.dataset == ds) & (that.pipeline == "N") & (that.condition == "L40")]
        rel = e["mean"].iloc[0] / (0.4 / np.sqrt(K[ds] - 1)) if len(e) else np.nan
        rows.append(" & ".join([
            NAMES[ds], f"{100 * a0['acc_mean']:.1f}",
            num(hyp, ds, "N", "D", 0.2), num(hyp, ds, "N", "D", 0.4), num(hyp, ds, "N", "I", 0.4),
            num(hyp, ds, "N", "G(L)", 0.4), num(hyp, ds, "N", "Delta", 0.4, paren_if=gl["conclusion"] != "positive"),
            num(hyp, ds, "N", "G*(L)", 0.4), num(hyp, ds, "N", "Delta*", 0.4, paren_if=gs["conclusion"] != "positive"),
            f"{rel:.2f}"]) + r" \\")
    write(os.path.join(out, "emp_results.tex"), [
        r"\begin{table}[tbp]", r"\centering", r"\scriptsize",
        r"\caption{Results for H1 and H2 (five seeds). $A_{0\%}$: clean accuracy of CE (\%). $D_\rho$ and the interaction $I_{0.4}$ "
        r"are differences of relative accuracy loss (percentage points); $G$ and $\Delta$ are differences of accuracy (points) "
        r"for loss correction with the estimated matrix (FC, main test) and with the true matrix (FC$^*$, exploratory). "
        r"$^{+}$/$^{-}$: 95\% interval above/below zero; values in parentheses are not evaluable because the advantage under "
        r"label noise alone is not positive. Last column: error of $\hat T$ under $L_{0.4}$ relative to the distance between "
        r"$T$ and $I$, $\|\hat T-T\|_F/\|T-I\|_F$. Results at $\rho=0.2$ are in \cref{app:emp-results}.}",
        r"\label{tab:emp-results}",
        r"\begin{tabular}{@{}lrrrrrrrrr@{}}", r"\toprule",
        r" & & \multicolumn{3}{c}{H1} & \multicolumn{2}{c}{H2: FC ($\hat T$)} & \multicolumn{2}{c}{H2$^*$: FC$^*$ ($T$)} & \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
        r"Modality & $A_{0\%}$ & $D_{0.2}$ & $D_{0.4}$ & $I_{0.4}$ & $G(L_{0.4})$ & $\Delta_{0.4}$ & $G^*(L_{0.4})$ & "
        r"$\Delta^*_{0.4}$ & $\hat T$ err. \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])

    # ---- H4 table
    rows = []
    for ds in FM_DATASETS:
        rf = ann[ann.dataset == ds].r_F
        gc = stat(hyp, ds, "N", "G*(C)")
        rla = {c: acc(ds, "N", "CE", c)["rla_mean"] for c in ("S", "C", "F")}
        rows.append(" & ".join([NAMES[ds], f"{100 * float(rf.iloc[0]):.1f}"] +
                               [f"{100 * rla[c]:.1f}" for c in ("S", "C", "F")] +
                               [num(hyp, ds, "N", s) for s in ("E", "E_class", "E_instance", "G*(C)", "G*(F)")] +
                               [num(hyp, ds, "N", "Delta_F", paren_if=gc["conclusion"] != "positive")]) + r" \\")
    write(os.path.join(out, "emp_h4.tex"), [
        r"\begin{table}[tbp]", r"\centering", r"\scriptsize",
        r"\caption{Labels from foundation models (H4, five seeds). $r_F$: error rate of the annotator (\%); RLA of CE under "
        r"symmetric noise at rate $r_F$ (S), class-conditional noise with the annotator's matrix (C) and the annotator's labels (F); "
        r"$E=\mathrm{RLA}(F)-\mathrm{RLA}(S)$, split into the effects of class structure, $\mathrm{RLA}(C)-\mathrm{RLA}(S)$, and of "
        r"instance dependence, $\mathrm{RLA}(F)-\mathrm{RLA}(C)$; $G^*$: advantage of FC$^*$ over CE (accuracy points); "
        r"$\Delta_F=G^*(F)-G^*(C)$. Marks as in \cref{tab:emp-results}.}",
        r"\label{tab:emp-h4}",
        r"\begin{tabular}{@{}lrrrrrrrrrr@{}}", r"\toprule",
        r" & & \multicolumn{3}{c}{RLA of CE} & \multicolumn{3}{c}{H4a} & \multicolumn{3}{c}{H4b} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(lr){9-11}",
        r"Modality & $r_F$ & S & C & F & $E$ & class & instance & $G^*(C)$ & $G^*(F)$ & $\Delta_F$ \\", r"\midrule"]
          + rows + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])

    # ---- appendix: accuracy per condition on the native pipeline
    conds = ["c0", "L20", "L40", "A20", "A40", "J20", "J40", "A40-l1", "A40-l3", "S", "C", "F"]
    head = ["Clean", "$L_{0.2}$", "$L_{0.4}$", "$A_{0.2}$", "$A_{0.4}$", "$J_{0.2}$", "$J_{0.4}$",
            "$A_{0.4}^{\\ell1}$", "$A_{0.4}^{\\ell3}$", "S", "C", "F"]
    rows = []
    for ds in DATASETS:
        for m, lab in (("CE", "CE"), ("FC", "FC"), ("FCstar", "FC$^*$")):
            cells = []
            for c in conds:
                r = acc(ds, "N", m, c)
                cells.append("" if r is None else f"{100 * r['acc_mean']:.1f}\\,{{\\tiny$\\pm${100 * (r['acc_hi'] - r['acc_mean']):.1f}}}")
            rows.append(" & ".join([NAMES[ds] if m == "CE" else "", lab] + cells) + r" \\")
        rows.append(r"\addlinespace")
    write(os.path.join(out, "emp_full_native.tex"), [
        r"\begin{table}[tbp]", r"\centering", r"\tiny", r"\setlength{\tabcolsep}{2.2pt}",
        r"\caption{Test accuracy (\%, mean and half-width of the 95\% interval over five seeds) of every configuration on the "
        r"native inputs. Empty cells are configurations that are not run (\cref{app:runs}).}",
        r"\label{tab:emp-full-native}",
        r"\begin{tabular}{@{}ll" + "r" * len(conds) + r"@{}}", r"\toprule",
        "Modality & Method & " + " & ".join(head) + r" \\", r"\midrule"] + rows[:-1]
          + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])

    # ---- appendix: frozen encoders (H3)
    rows = []
    for ds in FM_DATASETS:
        for m in ("CE", "FC"):
            cells = []
            for pl, c in (("EN", "c0"), ("EN", "L40"), ("EN", "A40"), ("EN", "J40"), ("EE", "A40"), ("EE", "J40")):
                r = acc(ds, pl, m, c)
                cells.append(f"{100 * r['acc_mean']:.1f}\\,{{\\tiny$\\pm${100 * (r['acc_hi'] - r['acc_mean']):.1f}}}")
            cells += [num(hyp, ds, pl, st, 0.4) for pl in ("N", "EN", "EE") for st in ("D",)] if m == "CE" else ["", "", ""]
            rows.append(" & ".join([NAMES[ds] if m == "CE" else "", m] + cells) + r" \\")
    write(os.path.join(out, "emp_full_frozen.tex"), [
        r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Frozen encoders with a linear classifier (H3, five seeds): test accuracy (\%, mean and half-width of the "
        r"95\% interval) when the native inputs are corrupted before encoding (EN) or the embeddings are perturbed (EE), and "
        r"$D_{0.4}$ for CE on the native inputs (N) and in each pipeline. The clean and label-only conditions are shared by "
        r"EN and EE.}",
        r"\label{tab:emp-full-frozen}",
        r"\begin{tabular}{@{}llrrrrrrrrr@{}}", r"\toprule",
        r" & & \multicolumn{4}{c}{EN} & \multicolumn{2}{c}{EE} & \multicolumn{3}{c}{$D_{0.4}$} \\",
        r"\cmidrule(lr){3-6}\cmidrule(lr){7-8}\cmidrule(lr){9-11}",
        r"Modality & Method & Clean & $L_{0.4}$ & $A_{0.4}$ & $J_{0.4}$ & $A_{0.4}$ & $J_{0.4}$ & N & EN & EE \\",
        r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])

    # ---- appendix: H1 and H2 at both rates, and the error of T-hat
    rows = []
    for ds in DATASETS:
        for rho in (0.2, 0.4):
            r = int(100 * rho)
            gl, gs = stat(hyp, ds, "N", "G(L)", rho), stat(hyp, ds, "N", "G*(L)", rho)
            err = []
            for c in (f"L{r}", f"J{r}"):
                e = that[(that.dataset == ds) & (that.pipeline == "N") & (that.condition == c)]
                err.append(f"{e['mean'].iloc[0]:.3f}" if len(e) else "--")
            rows.append(" & ".join([NAMES[ds] if rho == 0.2 else "", f"{rho:.1f}",
                                    num(hyp, ds, "N", "D", rho), num(hyp, ds, "N", "I", rho),
                                    num(hyp, ds, "N", "G(L)", rho), num(hyp, ds, "N", "G(J)", rho),
                                    num(hyp, ds, "N", "Delta", rho, paren_if=gl["conclusion"] != "positive"),
                                    num(hyp, ds, "N", "G*(L)", rho), num(hyp, ds, "N", "G*(J)", rho),
                                    num(hyp, ds, "N", "Delta*", rho, paren_if=gs["conclusion"] != "positive")] + err +
                                   [num(hyp, ds, "N", "errT(J)-errT(L)", rho)]) + r" \\")
        rows.append(r"\addlinespace")
    write(os.path.join(out, "emp_that.tex"), [
        r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\caption{H1 and H2 at both noise rates (five seeds), with the error of the estimated matrix, "
        r"$\|\hat T-T\|_F/K$, under label and joint noise and its paired change (in $10^{-2}$ for the last column). "
        r"Marks and parentheses as in \cref{tab:emp-results}.}",
        r"\label{tab:emp-that}",
        r"\begin{tabular}{@{}lrrrrrrrrrrrr@{}}", r"\toprule",
        r" & & \multicolumn{2}{c}{H1} & \multicolumn{3}{c}{FC ($\hat T$)} & \multicolumn{3}{c}{FC$^*$ ($T$)} & "
        r"\multicolumn{3}{c}{Error of $\hat T$} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}\cmidrule(lr){11-13}",
        r"Modality & $\rho$ & $D_\rho$ & $I_\rho$ & $G(L_\rho)$ & $G(J_\rho)$ & $\Delta_\rho$ & $G^*(L_\rho)$ & $G^*(J_\rho)$ & "
        r"$\Delta^*_\rho$ & $L_\rho$ & $J_\rho$ & change \\", r"\midrule"] + rows[:-1]
          + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    print("tables written to", out)


def e12(analysis, out):
    """Table of the exploratory experiments E1 and E2 from aggregate_e12.py.

    The headers name the level 7 chosen for every dataset by the calibration."""
    h = pd.concat([pd.read_csv(os.path.join(analysis, f)) for f in ("e1.csv", "e2.csv")], ignore_index=True)

    def n(ds, st, paren_if=False):
        r = h[(h.dataset == ds) & (h.statistic == st)]
        if not len(r) or pd.isna(r["mean"].iloc[0]):
            return "--"
        v = round(100 * r["mean"].iloc[0], 1) + 0.0
        txt = f"{v:.1f}".replace("-", "$-$") + MARK.get(r["conclusion"].iloc[0], "")
        return f"({txt})" if paren_if else txt

    def concl(ds, st):
        r = h[(h.dataset == ds) & (h.statistic == st)]
        return r["conclusion"].iloc[0] if len(r) else "n/a"

    rows = [" & ".join([NAMES[ds], n(ds, "RLA(L40)"), n(ds, "RLA(A40-s)"), n(ds, "I_s"), n(ds, "G*(L40)"),
                        n(ds, "G*(J40-s)"), n(ds, "Delta*_s", paren_if=concl(ds, "G*(L40)") != "positive"),
                        n(ds, "Acc~(c0)-Acc(c0)"), n(ds, "RLA~(L40)"), n(ds, "RLA~(A40)"), n(ds, "D~")]) + r" \\"
            for ds in DATASETS]
    write(os.path.join(out, "emp_e12.tex"), [
        r"\begin{table}[tbp]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Exploratory experiments (five seeds). E1: input noise at the strongest severity ($A^{7}_{0.4}$, $J^{7}_{0.4}$); "
        r"relative accuracy loss of CE and interaction $I_7$ (\%), advantage of FC$^*$ over CE (points) and "
        r"$\Delta^*_7=G^*(J^{7}_{0.4})-G^*(L_{0.4})$, in parentheses when not evaluable. E2: 40\% of the test inputs corrupted at "
        r"the middle severity; cost of the noisy test for the clean model, $\tilde A(c_0)-A(c_0)$ (points), relative loss on the "
        r"noisy test (\%) and $\tilde D=\widetilde{\mathrm{RLA}}(L_{0.4})-\widetilde{\mathrm{RLA}}(A_{0.4})$. Marks as in "
        r"\cref{tab:emp-results}.}",
        r"\label{tab:emp-e12}",
        r"\begin{tabular}{@{}lrrrrrrrrrr@{}}", r"\toprule",
        r" & \multicolumn{6}{c}{E1: strong input noise} & \multicolumn{4}{c}{E2: noisy test inputs} \\",
        r"\cmidrule(lr){2-7}\cmidrule(lr){8-11}",
        r"Modality & $\mathrm{RLA}(L_{0.4})$ & $\mathrm{RLA}(A^{7}_{0.4})$ & $I_7$ & $G^*(L_{0.4})$ & $G^*(J^{7}_{0.4})$ & "
        r"$\Delta^*_7$ & $\tilde A(c_0)-A(c_0)$ & $\widetilde{\mathrm{RLA}}(L_{0.4})$ & $\widetilde{\mathrm{RLA}}(A_{0.4})$ & "
        r"$\tilde D$ \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    print("E1/E2 table written to", out)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--analysis", help="analysis folder of aggregate.py (grid)")
    p.add_argument("--e12", help="analysis folder of aggregate_e12.py (E1 and E2)")
    p.add_argument("--out", required=True)
    a = p.parse_args()
    if a.analysis:
        main(a.analysis, a.out)
    if a.e12:
        e12(a.e12, a.out)
